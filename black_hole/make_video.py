def palette(temp):
    """Blackbody-ish colour ramp: 0.2 deep red ... 1.0 white ... 1.6 blue-white."""
    temp = np.asarray(temp, np.float32)
    return np.stack([np.interp(temp, PALETTE_T, PALETTE_C[:, c]) for c in range(3)], axis=-1).astype(np.float32)


def fractal(shape, sigmas, rng, weights=None):
    weights = weights or [1.0] * len(sigmas)
    out = np.zeros(shape, np.float32)
    for s, w in zip(sigmas, weights):
        n = ndimage.gaussian_filter(rng.standard_normal(shape).astype(np.float32), s, mode='wrap')
        out += w * n / (n.std() + 1e-9)
    return out / sum(weights)


