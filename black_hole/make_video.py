def tokenize(text):
    """Display words; stand-alone punctuation (like the dash) sticks to the word before it."""
    out = []
    for tok in text.split():
        if out and not re.search(r'[A-Za-z0-9]', tok):
            out[-1] = out[-1] + ' ' + tok
        else:
            out.append(tok)
    return out


def norm_word(w):
    return re.sub(r'[^a-z0-9]', '', w.lower().replace('’', "'"))


