def main():
    global A, TL, EV, PHRASES
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--workers', type=int, default=os.cpu_count() or 4)
    ap.add_argument('--stills', action='store_true', help='only render preview stills of key moments')
    args = ap.parse_args()
    os.makedirs(BUILD, exist_ok=True)
    t_start = time.time()

    log('[1/6] voice')
    backend, setting, lines, TL = synth_voice()
    log(f'  using {backend} ({setting})')

    log('[2/6] timeline')
    EV = cue_times(TL)
    A = Assets()
    PHRASES = build_phrases(TL, A.f_cap)
    S = TL['scenes']
    for i, s in enumerate(SCRIPT):
        log(f'  scene {i + 1} {s["key"]:<9} {S[i]:5.2f}-{S[i + 1]:5.2f}s  voice {TL["vo_start"][i]:5.2f}-{TL["vo_end"][i]:5.2f}s')
    log('  cues: ' + ', '.join(f'{k}={v:.2f}' for k, v in EV.items()))
    with open(os.path.join(BUILD, 'timeline.json'), 'w') as f:
        json.dump(dict(backend=backend, setting=setting, timeline=TL, cues=EV, phrases=PHRASES), f, indent=1)

    if args.stills:
        log('[stills]')
        log(f'  -> {render_stills()}')
        return

    log('[3/6] audio')
    wav, st = build_audio(TL, EV, lines)
    log(f'  voice {st["vo_lufs"]:.1f} LUFS, bed under voice {st["bed_under_vo_db"]:.1f} dB, '
        f'mix {st["mix_lufs"]:.1f} LUFS, peak {st["peak_db"]:.1f} dBFS')

    log('[4/6] video')
    files = render_scenes(args.workers)

    log('[5/6] mux')
    mux(files, wav)

    log('[6/6] verify')
    dur = verify(os.path.join(BUILD, 'vo_only.wav'))
    if abs(dur - DURATION) > 0.0005:
        log(f'  WARNING: duration {dur:.3f} s != {DURATION} s')
    log(f'done in {(time.time() - t_start) / 60:.1f} min -> {OUTPUT}')


if __name__ == '__main__':
    main()
