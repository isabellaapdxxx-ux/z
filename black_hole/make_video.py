def _envelope(x, hop):
    n = len(x) // hop
    return np.sqrt(np.mean(x[:n * hop].reshape(n, hop) ** 2, axis=1) + 1e-12)


def trim_silence(x, thr_rel=0.02, pad=0.015):
    e = _envelope(x, 240)
    idx = np.where(e > e.max() * thr_rel)[0]
    if len(idx) == 0:
        return x
    a = max(0, idx[0] * 240 - int(pad * SR))
    b = min(len(x), (idx[-1] + 1) * 240 + int(pad * 2 * SR))
    return x[a:b]


def estimate_word_times(x, words, weights):
    """Word start/end times inside one TTS clip (Kokoro gives no timestamps).

    Pauses in the audio are matched to the commas in the text; the words between
    them are spread by phoneme count, and each boundary is snapped to the nearest
    dip in the loudness envelope."""
    hop = 240                                   # 5 ms
    e = ndimage.uniform_filter1d(_envelope(x, hop), 3)
    thr = e.max() * 0.06
    loud = np.where(e > thr)[0]
    first, last = (loud[0], loud[-1] + 1) if len(loud) else (0, len(e))
    quiet = e < thr
    runs, i = [], first
    while i < last:
        if quiet[i]:
            j = i
            while j < last and quiet[j]:
                j += 1
            if j - i >= 12:                     # >= 60 ms of silence
                runs.append((i, j))
            i = j
        else:
            i += 1
    pauses = [k for k, w in enumerate(words[:-1]) if re.search(r'[,;:]$', w)]
    runs = sorted(sorted(runs, key=lambda r: r[0] - r[1])[:len(pauses)])
    if len(runs) != len(pauses):
        pauses, runs = [], []
    # segments of words between pauses
    seg_bounds, start_w, start_f = [], 0, first
    for k, (ra, rb) in zip(pauses, runs):
        seg_bounds.append((start_w, k + 1, start_f, ra))
        start_w, start_f = k + 1, rb
    seg_bounds.append((start_w, len(words), start_f, last))
    times = [None] * len(words)
    for wa, wb, fa, fb in seg_bounds:
        wts = np.array(weights[wa:wb], float)
        edges = fa + (fb - fa) * np.concatenate([[0], np.cumsum(wts) / wts.sum()])
        for m in range(1, len(edges) - 1):      # snap inner boundaries to envelope dips
            c = int(round(edges[m]))
            lo, hi = max(fa + 1, c - 12), min(fb - 1, c + 12)
            if hi > lo:
                edges[m] = lo + int(np.argmin(e[lo:hi]))
        for m in range(wb - wa):
            times[wa + m] = (edges[m] * hop / SR, edges[m + 1] * hop / SR)
    return times


class KokoroTTS:
    name = 'kokoro'

    def __init__(self):
        for f in ('kokoro-v1.0.onnx', 'voices-v1.0.bin'):
            path = os.path.join(KOKORO_DIR, f)
            if not os.path.exists(path):
                os.makedirs(KOKORO_DIR, exist_ok=True)
                log(f'  downloading {f} ...')
                try:
                    urllib.request.urlretrieve(KOKORO_URL + f, path + '.part')
                except OSError:
                    subprocess.run(['curl', '-sSL', '-o', path + '.part', KOKORO_URL + f], check=True)
                os.replace(path + '.part', path)
        import logging
        logging.getLogger('phonemizer').setLevel(logging.ERROR)
        from kokoro_onnx import Kokoro
        self.k = Kokoro(os.path.join(KOKORO_DIR, 'kokoro-v1.0.onnx'),
                        os.path.join(KOKORO_DIR, 'voices-v1.0.bin'))

    def weights(self, words):
        out = []
        for w in words:
            ph = self.k.tokenizer.phonemize(re.sub(r'[^A-Za-z\']', '', w) or 'a', 'en-us')
            out.append(len(re.sub(r'[ˈˌː.,!?…—\s]', '', ph)) + 1.0)
        return out

    def line(self, text, speed):
        """One clip per VO line, built from its sentences with controlled pauses."""
        words = tokenize(text)
        chunks, cur = [], []
        for w in words:
            cur.append(w)
            if re.search(r'[.…—?!]$', w):
                chunks.append(cur)
                cur = []
        if cur:
            chunks.append(cur)
        audio, times, t = [], [], 0.0
        for ci, ch in enumerate(chunks):
            say = ' '.join(ch).replace('—', ',').replace('…', ',').strip()
            say = re.sub(r',$', ',', say)
            x, sr = self.k.create(say, voice=KOKORO_VOICE, speed=speed, lang='en-us')
            x = signal.resample_poly(np.asarray(x, np.float64), SR, sr)
            x = trim_silence(x)
            for (a, b) in estimate_word_times(x, ch, self.weights(ch)):
                times.append((t + a, t + b))
            audio.append(x)
            t += len(x) / SR
            if ci < len(chunks) - 1:
                gap = CHUNK_PAUSE.get(ch[-1][-1], 0.25)
                audio.append(np.zeros(int(gap * SR)))
                t += gap
        return np.concatenate(audio), [dict(text=w, t0=a, t1=b) for w, (a, b) in zip(words, times)]


class EdgeTTS:
    name = 'edge-tts'

    def __init__(self):
        import edge_tts  # noqa: F401  (import error -> fallback)
        self.proxy = os.environ.get('HTTPS_PROXY') or os.environ.get('https_proxy') or None

    async def _run(self, text, rate):
        import edge_tts
        comm = edge_tts.Communicate(text, EDGE_VOICE, rate=rate, boundary='WordBoundary',
                                    proxy=self.proxy, connect_timeout=10, receive_timeout=40)
        audio, marks = bytearray(), []
        async for ch in comm.stream():
            if ch['type'] == 'audio':
                audio.extend(ch['data'])
            elif ch['type'] == 'WordBoundary':
                marks.append((ch['offset'] / 1e7, (ch['offset'] + ch['duration']) / 1e7, ch['text']))
        return bytes(audio), marks

    def line(self, text, rate):
        mp3, marks = asyncio.run(asyncio.wait_for(self._run(text, rate), 90))
        if not mp3:
            raise RuntimeError('edge-tts returned no audio')
        os.makedirs(BUILD, exist_ok=True)
        src, dst = os.path.join(BUILD, '_edge.mp3'), os.path.join(BUILD, '_edge.wav')
        with open(src, 'wb') as f:
            f.write(mp3)
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src, '-ar', str(SR), '-ac', '1', dst], check=True)
        x = wavfile.read(dst)[1].astype(np.float64) / 32768.0
        words = tokenize(text)
        out, mi = [], 0
        for w in words:                       # match boundary events to display words
            nw = norm_word(w)
            j = mi
            while j < len(marks) and norm_word(marks[j][2]) != nw:
                j += 1
            if j < len(marks):
                out.append(dict(text=w, t0=marks[j][0], t1=marks[j][1]))
                mi = j + 1
            else:
                out.append(None)
        for k, o in enumerate(out):           # fill any unmatched word by interpolation
            if o is None:
                prev = out[k - 1]['t1'] if k else 0.0
                nxt = next((q['t0'] for q in out[k + 1:] if q), len(x) / SR)
                out[k] = dict(text=words[k], t0=prev, t1=(prev + nxt) / 2)
        return x, out


def voice_fx(x):
    """Gentle polish: rumble cut, a touch of warmth, light compression."""
    x = signal.sosfilt(signal.butter(2, 75, 'highpass', fs=SR, output='sos'), x)
    warm = signal.sosfilt(signal.butter(2, [120, 380], 'bandpass', fs=SR, output='sos'), x)
    x = x + 0.18 * warm
    env = ndimage.maximum_filter1d(np.abs(x), int(0.01 * SR))
    env = ndimage.uniform_filter1d(env, int(0.03 * SR))
    ref = np.percentile(env[env > env.max() * 0.05], 90)
    gain = np.where(env > ref * 0.5, (np.maximum(env, ref * 0.5) / (ref * 0.5)) ** (-0.3), 1.0)
    x = x * gain
    return x / (np.abs(x).max() + 1e-9) * 0.89


def synth_voice():
    """Returns (backend, setting, [dict(audio, words)] per line), cached in build/voice/."""
    os.makedirs(os.path.join(BUILD, 'voice'), exist_ok=True)
    backends = []
    try:
        backends.append((EdgeTTS(), EDGE_RATES))
    except Exception as e:  # noqa: BLE001
        log(f'  edge-tts unavailable ({e})')
    backends.append((None, KOKORO_SPEEDS))      # Kokoro created lazily
    for eng, settings in backends:
        for setting in settings:
            key = hashlib.sha1(json.dumps([eng.name if eng else 'kokoro', EDGE_VOICE if eng else KOKORO_VOICE,
                                           setting, [s['vo'] for s in SCRIPT], 3]).encode()).hexdigest()[:12]
            cache = os.path.join(BUILD, 'voice', key + '.npz')
            if os.path.exists(cache):
                d = np.load(cache, allow_pickle=True)
                lines = [dict(audio=a, words=w) for a, w in zip(d['audio'], d['words'])]
                name = str(d['backend'])
            else:
                try:
                    if eng is None:
                        eng = KokoroTTS()
                    lines = []
                    for s in SCRIPT:
                        a, w = eng.line(s['vo'], setting)
                        lines.append(dict(audio=voice_fx(a), words=w))
                    name = eng.name
                except Exception as e:  # noqa: BLE001
                    log(f'  {eng.name if eng else "kokoro"} failed: {type(e).__name__}: {str(e)[:160]}')
                    break                          # try the next backend
                np.savez(cache, audio=np.array([l['audio'] for l in lines], dtype=object),
                         words=np.array([l['words'] for l in lines], dtype=object), backend=name)
            tl = solve_timeline(lines)
            log(f'  {name} @ {setting}: lines ' + ', '.join(f'{len(l["audio"]) / SR:.2f}s' for l in lines)
                + ('  -> fits' if tl else '  -> too long, speeding up'))
            if tl:
                return name, setting, lines, tl
    raise SystemExit('voice-over does not fit in 30 s; shorten SCRIPT')


# ============================================================================ 2. timeline

def solve_timeline(lines):
    """Scene boundaries + absolute word times. None if the voice does not fit.

    Each boundary stays at its nominal time when possible, moving later only if the
    previous line runs long (and earlier only if the remaining lines need the room)."""
    durs = [len(l['audio']) / SR for l in lines]
    gap = 0.2                                        # silence before a cut
    scene_t, vo_t, prev_end = [0.0], [SCRIPT[0]['lead']], SCRIPT[0]['lead'] + durs[0]
    for i in range(1, len(SCRIPT)):
        lo = prev_end + gap
        hi = DURATION - END_TAIL - sum(SCRIPT[j]['lead'] + durs[j] for j in range(i, len(SCRIPT))) \
            - gap * (len(SCRIPT) - 1 - i)
        if hi < lo:
            return None
        st = min(max(SCRIPT[i]['start'], lo), hi)
        st = math.ceil(st * FPS - 1e-6) / FPS if st < hi - 1 / FPS else math.floor(hi * FPS + 1e-6) / FPS
        if st < lo - 1e-6:
            return None
        scene_t.append(st)
        vo_t.append(st + SCRIPT[i]['lead'])
        prev_end = vo_t[-1] + durs[i]
    if prev_end > DURATION - END_TAIL + 1e-6:
        return None
    scene_t.append(DURATION)
    if np.diff(scene_t).min() < 3.5:
        return None
    words = []
    for i, (l, v) in enumerate(zip(lines, vo_t)):
        for w in l['words']:
            words.append(dict(text=w['text'], t0=v + w['t0'], t1=v + w['t1'], line=i))
    return dict(scenes=scene_t, vo_start=vo_t, words=words, vo_end=[v + d for v, d in zip(vo_t, durs)])


def word_time(tl, line, key, which='t0'):
    for w in tl['words']:
        if w['line'] == line and norm_word(w['text']).startswith(key):
            return w[which]
    raise KeyError(f'cue word {key!r} not in line {line}')


def cue_times(tl):
    """Visual / sound cues locked to the narration."""
    S = tl['scenes']
    ev = dict(
        fuel=word_time(tl, 1, 'fuel'),
        gravity=word_time(tl, 1, 'gravity'),
        collapse=word_time(tl, 1, 'collapses') - 0.05,
        explode=word_time(tl, 1, 'explodes', 't1') + 0.06,
        dense=word_time(tl, 2, 'dense'),
        light=word_time(tl, 2, 'light'),
        horizon=word_time(tl, 2, 'event'),
        bends=word_time(tl, 3, 'bends'),
        anything=word_time(tl, 3, 'anything'),
        stretched=word_time(tl, 3, 'stretched'),
        pulled=word_time(tl, 3, 'pulled'),
        title=max(word_time(tl, 4, 'time'), S[4] + 1.2),
    )
    ev['explode'] = min(ev['explode'], S[2] - 0.6)
    ev['bh'] = max(ev['dense'] - 0.15, S[2] + 0.9)
    ev['obj_in'] = S[3] + 0.2
    ev['obj_end'] = S[4] + 0.15
    return ev


def build_phrases(tl, font):
    """Caption pages: sentence/clause sized, at most two lines."""
    words = tl['words']
    groups, cur = [], []
    for i, w in enumerate(words):
        cur.append(i)
        end_line = i + 1 == len(words) or words[i + 1]['line'] != w['line']
        hard = re.search(r'[.…—?!]$', w['text'])
        soft = w['text'].endswith(',') and len(cur) >= 3
        if end_line or hard or soft:
            groups.append(cur)
            cur = []
    out = []
    for g in groups:
        text = ' '.join(words[i]['text'] for i in g)
        if len(g) > 9 or font.getlength(text) > 2 * CAPTION_MAXW - 60:
            best = min(range(1, len(g)), key=lambda k: abs(
                font.getlength(' '.join(words[i]['text'] for i in g[:k])) -
                font.getlength(' '.join(words[i]['text'] for i in g[k:]))))
            out += [g[:best], g[best:]]
        else:
            out.append(g)
    phrases = []
    for k, g in enumerate(out):
        t0 = words[g[0]]['t0'] - 0.12
        t1 = words[g[-1]]['t1'] + 0.45
        if k + 1 < len(out):
            t1 = min(t1, words[out[k + 1][0]]['t0'] - 0.14)
        t1 = min(t1, DURATION - 0.35)
        phrases.append(dict(idx=g, t0=t0, t1=t1))
    return phrases


# ============================================================================ 3. audio

def _sos(kind, f, order=2):
    return signal.butter(order, f, btype=kind, fs=SR, output='sos')


def lp(x, f, o=2):
    return signal.sosfilt(_sos('lowpass', f, o), x, axis=0)


def hp(x, f, o=2):
    return signal.sosfilt(_sos('highpass', f, o), x, axis=0)


def bp(x, lo, hi, o=2):
    return signal.sosfilt(_sos('bandpass', [lo, hi], o), x, axis=0)


def tt(d):
    return np.arange(int(d * SR)) / SR


def stereo(x, pan=0.0, width=0.0, seed=0):
    a = (pan + 1) * math.pi / 4
    s = np.stack([x * math.cos(a), x * math.sin(a)], axis=1) * math.sqrt(2)
    if width > 0:                               # decorrelate a little for size
        d = int(0.011 * SR)
        s[d:, 1] = (1 - width) * s[d:, 1] + width * s[:-d, 1]
    return s


_IR = {}


def reverb(x, decay=2.5, mix=0.3, bright=5000, pre=0.02, seed=3):
    key = (decay, bright, pre, seed)
    if key not in _IR:
        rng = np.random.default_rng(seed)
        n = int(decay * SR)
        t = np.arange(n) / SR
        ir = rng.standard_normal((n, 2)) * np.exp(-6.9 * t / decay)[:, None]
        ir = lp(ir, bright)
        ir = np.concatenate([np.zeros((int(pre * SR), 2)), ir])
        _IR[key] = ir / np.sqrt((ir ** 2).sum(axis=0, keepdims=True))
    ir = _IR[key]
    if x.ndim == 1:
        x = stereo(x)
    wet = np.stack([signal.fftconvolve(x[:, c], ir[:, c])[:len(x)] for c in range(2)], axis=1)
    return x * (1 - mix) + wet * mix * 1.6


def tail(x, extra):
    pad = np.zeros((int(extra * SR),) + x.shape[1:])
    return np.concatenate([x, pad])


def noise_sweep(fc, rng):
    """Noise whose spectral centre follows the curve fc (Hz per sample)."""
    n = len(fc)
    x = rng.standard_normal(n)
    out = np.zeros(n)
    for c in np.geomspace(90, 12000, 16):
        wgt = np.exp(-(np.log(fc / c) / 0.38) ** 2)
        if wgt.max() < 1e-3:
            continue
        out += bp(x, c / 1.35, min(c * 1.35, SR / 2 - 100)) * wgt
    return out


class Bus:
    def __init__(self):
        self.b = np.zeros((NS, 2))

    def add(self, x, t, gain=1.0, pan=0.0):
        if x.ndim == 1:
            x = stereo(x, pan)
        i = int(round(t * SR))
        a, b = max(i, 0), min(i + len(x), NS)
        if b > a:
            self.b[a:b] += x[a - i:b - i] * gain


def sfx_whoosh(rng, d=1.3, peak=0.62):
    t = tt(d)
    p = t / d
    up = np.clip(t / peak, 0, 1)
    fc = np.where(t < peak, 250 * (5000 / 250) ** (up ** 1.5), 5000 * (600 / 5000) ** ((t - peak) / (d - peak)))
    env = np.where(t < peak, up ** 2.2, np.exp(-(t - peak) / 0.16))
    x = noise_sweep(fc, rng) * env
    pan = np.clip(-0.7 + 1.4 * p, -1, 1)
    a = (pan + 1) * np.pi / 4
    s = np.stack([x * np.cos(a), x * np.sin(a)], axis=1) * 1.4
    return reverb(s, 1.2, 0.25)


def sfx_riser(rng, d):
    t = tt(d)
    p = t / d
    fc = 300 * (9000 / 300) ** (p ** 1.6)
    nz = noise_sweep(fc, rng) * 0.8
    f = 98 * 2 ** (2.5 * p ** 1.8)
    ph = 2 * np.pi * np.cumsum(f) / SR
    tone = (signal.sawtooth(ph) + signal.sawtooth(ph * 1.007) + 0.5 * signal.sawtooth(ph * 2.003)) / 2.5
    tone = lp(tone, 900) * (1 - p ** 2) + lp(tone, 6000) * p ** 2   # filter opens as it rises
    trem_rate = 4 + 18 * p ** 2
    trem = 0.75 + 0.25 * np.sin(2 * np.pi * np.cumsum(trem_rate) / SR)
    x = (nz + tone * 0.55) * trem * p ** 2.4
    x[-int(0.015 * SR):] *= np.linspace(1, 0, int(0.015 * SR))
    return reverb(stereo(x, 0, 0.5), 1.8, 0.3)


def sfx_boom(rng, size=1.0):
    t = tt(6.0)
    f = 27 + 75 * np.exp(-t / 0.16)
    sub = np.tanh(2.2 * np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / (1.3 * size)))
    nz = rng.standard_normal(len(t))
    body = lp(nz, 650) * np.exp(-t / 0.32) * 1.6
    crack = hp(nz, 1800) * np.exp(-t / 0.035) * 0.5
    rumble = lp(rng.standard_normal(len(t)), 110, 4) * np.exp(-t / 2.2) * 6
    x = sub * 0.95 + body + crack + rumble * size
    x = np.tanh(x * 1.3) * 0.8
    return reverb(stereo(x, 0, 0.7), 3.8, 0.42, bright=3000)


def sfx_suck(rng, d=1.4):
    """Reversed-swell implosion leading into the boom."""
    t = tt(d)
    p = t / d
    fc = 200 * (3500 / 200) ** (p ** 2)
    x = noise_sweep(fc, rng) * p ** 3.5
    sub_f = 40 + 30 * p
    x += np.sin(2 * np.pi * np.cumsum(sub_f) / SR) * p ** 3 * 0.8
    x[-int(0.01 * SR):] *= np.linspace(1, 0, int(0.01 * SR))
    return stereo(x, 0, 0.6)


def sfx_thud(rng, size=1.0):
    t = tt(3.0)
    f = 30 + 40 * np.exp(-t / 0.12)
    x = np.tanh(1.8 * np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.7))
    x += lp(rng.standard_normal(len(t)), 300) * np.exp(-t / 0.25) * 0.8
    return reverb(stereo(x * size, 0, 0.5), 3.0, 0.35, bright=2500)


def sfx_shimmer(rng, d):
    t = tt(d)
    out = np.zeros((len(t), 2))
    notes = [587.33, 739.99, 880.0, 1108.73, 1318.51, 1760.0, 2217.46, 2637.0]
    for k, f in enumerate(notes):
        trem = 0.6 + 0.4 * np.sin(2 * np.pi * rng.uniform(0.15, 0.6) * t + rng.uniform(0, 6))
        vib = 1 + 0.002 * np.sin(2 * np.pi * rng.uniform(3, 5) * t)
        x = np.sin(2 * np.pi * f * np.cumsum(vib) / SR) * trem / (1 + 0.35 * k)
        out += stereo(x, rng.uniform(-0.7, 0.7))
    for _ in range(26):                          # sparkles
        s = rng.uniform(0, d - 0.3)
        f = rng.uniform(2200, 6500)
        n = int(0.35 * SR)
        a = int(s * SR)
        ping = np.sin(2 * np.pi * f * np.arange(n) / SR) * np.exp(-np.arange(n) / SR / 0.07) * 0.25
        out[a:a + n] += stereo(ping, rng.uniform(-0.9, 0.9))[:len(out) - a]
    return reverb(out, 4.5, 0.6, bright=9000)


def build_bed(tl, ev, rng):
    S = tl['scenes']
    t = np.arange(NS) / SR
    bus = Bus()

    # sub-bass drone that builds through the film (D), opening up as it grows
    f0 = 36.71
    raw = (np.sin(2 * np.pi * f0 * t + 0.4 * np.sin(2 * np.pi * 0.07 * t))
           + 0.7 * np.sin(2 * np.pi * 2 * f0 * 1.002 * t)
           + 0.35 * np.sin(2 * np.pi * 3 * f0 * t + 1.0)
           + 0.3 * np.sin(2 * np.pi * 1.5 * f0 * 0.998 * t))
    raw = np.tanh(1.6 * raw)
    build = np.interp(t, [0, S[1], ev['explode'], S[2], S[3], S[4], 28.5, 30],
                      [0.30, 0.42, 0.55, 0.62, 0.78, 0.95, 1.0, 0.0])
    drone = lp(raw, 110) * (1 - build) + lp(raw, 420) * build
    drone *= build * (0.85 + 0.15 * np.sin(2 * np.pi * 0.11 * t))
    bus.add(stereo(drone, 0, 0.3), 0, 0.55)

    # dark pad: Dm(add9) -> Bbmaj7 -> Gm6 -> D (wonder)
    chords = [(0, S[2], [73.42, 110.0, 164.81, 174.61]),
              (S[2], S[3], [58.27, 87.31, 146.83, 220.0]),
              (S[3], S[4], [49.0, 73.42, 116.54, 164.81]),
              (S[4], DURATION, [73.42, 110.0, 185.0, 220.0, 329.63])]
    pad = np.zeros(NS)
    for a, b, notes in chords:
        env = smoothstep(a - 0.8, a + 1.2, t) * (1 - smoothstep(b - 0.4, b + 1.0, t))
        seg = np.zeros(NS)
        for f in notes:
            for det in (0.996, 1.004):
                seg += signal.sawtooth(2 * np.pi * f * det * t + rng.uniform(0, 6))
        pad += seg * env / len(notes)
    pad = lp(pad, 700, 2) * np.interp(t, [0, 5, 11, 25, 28.5, 30], [0.5, 0.6, 0.8, 1.0, 1.0, 0])
    bus.add(reverb(stereo(pad, 0, 0.6), 3.0, 0.45, bright=2500), 0, 0.10)

    # low rumble
    brown = np.cumsum(rng.standard_normal(NS))
    brown = lp(hp(brown, 18, 2), 90, 3)
    brown /= np.abs(brown).max()
    rum_env = np.interp(t, [0, S[1], ev['collapse'], ev['explode'], ev['explode'] + 3, S[3], S[4], 27, 30],
                        [0.15, 0.25, 0.5, 1.0, 0.6, 0.55, 0.8, 0.35, 0.0])
    bus.add(stereo(brown * rum_env * (0.8 + 0.2 * np.sin(2 * np.pi * 0.13 * t)), 0, 0.8), 0, 0.9)

    # whoosh on each scene change (peaks at the cut)
    for b in S[1:-1]:
        bus.add(sfx_whoosh(rng), b - 0.62, 0.45)

    # supernova: implosion swell, boom
    d = max(0.6, ev['explode'] - ev['collapse'])
    bus.add(sfx_suck(rng, d), ev['explode'] - d, 0.55)
    bus.add(sfx_boom(rng, 1.0), ev['explode'], 1.0)

    # black hole forms: low thud
    bus.add(sfx_thud(rng, 0.8), ev['bh'], 0.8)

    # riser into the event-horizon reveal, small hit on it
    r1 = 2.6
    bus.add(sfx_riser(rng, r1), ev['horizon'] - r1, 0.30)
    bus.add(sfx_thud(rng, 0.5), ev['horizon'], 0.45)

    # riser through the spaghettification, hit on the pull-back
    r2 = max(2.5, S[4] - ev['anything'])
    bus.add(sfx_riser(rng, r2), S[4] - r2, 0.40)
    bus.add(sfx_boom(rng, 0.6), S[4], 0.55)

    # shimmer / reverb tail for the finale
    sh = sfx_shimmer(rng, DURATION - S[4])
    sh *= smoothstep(0, 1.2, tt(len(sh) / SR))[:, None]
    bus.add(sh, S[4], 0.16)

    b = bus.b
    fade = 1 - smoothstep(DURATION - 1.4, DURATION - 0.02, t)
    return b * fade[:, None]


def lufs(x):
    import pyloudnorm
    return pyloudnorm.Meter(SR).integrated_loudness(x)


def limiter(x, ceiling_db=CEILING_DB):
    ceil = 10 ** (ceiling_db / 20)
    det = np.abs(signal.resample_poly(x, 4, 1, axis=0)).max(axis=1)      # ~true peak
    det = det.reshape(-1, 4).max(axis=1)[:len(x)]
    g = np.minimum(1.0, ceil / np.maximum(det, 1e-9))
    look = int(0.004 * SR)
    g = ndimage.minimum_filter1d(g, 2 * look + 1)
    g = ndimage.uniform_filter1d(g, look)
    rel = int(0.06 * SR)                                                  # smooth release
    g = np.minimum(g, ndimage.uniform_filter1d(ndimage.minimum_filter1d(g, rel), rel))
    return np.clip(x * g[:, None], -ceil, ceil)


def build_audio(tl, ev, lines):
    rng = np.random.default_rng(11)
    vo = np.zeros(NS)
    for l, v in zip(lines, tl['vo_start']):
        a = int(round(v * SR))
        vo[a:a + len(l['audio'])] += l['audio'][:NS - a]
    vo_st = reverb(stereo(vo), 1.1, 0.07, bright=6000, pre=0.01)

    bed = build_bed(tl, ev, rng)

    # sidechain: the bed drops DUCK_DEPTH_DB while the voice speaks
    env = ndimage.maximum_filter1d(np.abs(vo), int(0.03 * SR))
    active = (env > 0.02).astype(float)
    active = ndimage.maximum_filter1d(active, int(0.25 * SR))
    active = ndimage.gaussian_filter1d(active, 0.06 * SR)
    duck = 10 ** (-DUCK_DEPTH_DB * active / 20)
    bed_d = bed * duck[:, None]

    # level the bed so it sits DUCK_UNDER_VO_DB under the voice while it speaks
    m = active > 0.9
    l_vo = lufs(vo_st[m])
    l_bed = lufs(bed_d[m])
    g = 10 ** ((l_vo - DUCK_UNDER_VO_DB - l_bed) / 20)
    bed_d *= g
    mix = vo_st + bed_d
    for _ in range(3):
        mix = mix * 10 ** ((TARGET_LUFS - lufs(mix)) / 20)
        mix = limiter(mix)
    mix[-int(0.02 * SR):] *= np.linspace(1, 0, int(0.02 * SR))[:, None]
    stats = dict(vo_lufs=l_vo, bed_under_vo_db=l_vo - lufs(bed_d[m]),
                 mix_lufs=lufs(mix), peak_db=20 * np.log10(np.abs(mix).max()))
    path = os.path.join(BUILD, 'mix.wav')
    wavfile.write(path, SR, (mix * 32767).astype(np.int16))
    wavfile.write(os.path.join(BUILD, 'vo_only.wav'), SR, (vo * 32767).astype(np.int16))
    return path, stats


