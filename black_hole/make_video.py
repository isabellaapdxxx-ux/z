def clamp01(x):
    return np.clip(x, 0.0, 1.0)


def smoothstep(a, b, x):
    t = clamp01((np.asarray(x, dtype=np.float64) - a) / (b - a))
    return t * t * (3 - 2 * t)


def ease_io(x):
    return smoothstep(0.0, 1.0, x)


def ease_out3(x):
    x = clamp01(x)
    return 1 - (1 - x) ** 3


def ease_out_back(x, k=1.6):
    x = clamp01(x)
    return 1 + (k + 1) * (x - 1) ** 3 + k * (x - 1) ** 2


def lerp(a, b, t):
    return a + (b - a) * t


