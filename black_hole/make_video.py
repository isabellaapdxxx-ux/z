class Cam:
    """2D camera: world (0,0) is the subject. zoom scales, shake offsets, bg pans the starfield."""

    def __init__(self, zoom=1.0, shake=(0.0, 0.0), bg=(0.0, 0.0)):
        self.zoom = zoom
        self.shake = np.array(shake, float)
        self.bg = np.array(bg, float)

    def center(self):
        return ANCHOR + self.shake


def splat(acc, x, y, flux_rgb, sig_idx):
    """Additively draw gaussian dots into acc (3, H*W)."""
    R, sub = A.spr_r, A.spr_sub
    xi, yi = np.floor(x).astype(np.int64), np.floor(y).astype(np.int64)
    ok = (xi >= R) & (xi < W - R) & (yi >= R) & (yi < H - R) & (flux_rgb.max(axis=1) > 1e-4)
    if not ok.any():
        return
    xi, yi, x, y, f, si = xi[ok], yi[ok], x[ok], y[ok], flux_rgb[ok], np.asarray(sig_idx)[ok]
    fx = np.clip(((x - xi) * sub).astype(int), 0, sub - 1)
    fy = np.clip(((y - yi) * sub).astype(int), 0, sub - 1)
    spr = A.sprites[si, fx, fy]                                   # (n, k)
    idx = ((yi * W + xi)[:, None] + A.spr_off[None, :]).ravel()
    for c in range(3):
        acc[c] += np.bincount(idx, weights=(spr * f[:, c:c + 1]).ravel(), minlength=H * W)


def lens_images(px, py, lens):
    """Point-lens images of source points (screen px). Returns list of (x, y, magnif, stretch, tangent)."""
    cx, cy, rs, th_e, shadow = lens
    bx, by = (px - cx) / rs, (py - cy) / rs
    beta = np.hypot(bx, by) + 1e-6
    ux, uy = bx / beta, by / beta
    root = np.sqrt(beta ** 2 + 4 * th_e ** 2)
    out = []
    for th in ((beta + root) / 2, (beta - root) / 2):
        q = (th_e / np.maximum(np.abs(th), 1e-4)) ** 2
        mu_t = 1 / np.maximum(np.abs(1 - q), 0.06)
        mu_r = 1 / (1 + q)
        vis = smoothstep(shadow * 1.0, shadow * 1.06, np.abs(th))
        out.append((cx + ux * th * rs, cy + uy * th * rs, np.minimum(mu_t * mu_r, 9.0) * vis,
                    mu_t / mu_r, np.abs(th) * rs, np.arctan2(uy * np.sign(th), ux * np.sign(th))))
    return out


def render_stars(acc, t, cam, lens):
    d = A.st_d
    z = cam.zoom ** d
    drift = np.array([-6.0, -2.5]) * t
    px = ANCHOR[0] + cam.shake[0] + (A.st_p[:, 0] + (drift[0] + cam.bg[0]) * d) * z
    py = ANCHOR[1] + cam.shake[1] + (A.st_p[:, 1] + (drift[1] + cam.bg[1]) * d) * z
    tw = 1 + A.st_tw[0] * np.sin(A.st_tw[1] * t + A.st_tw[2])
    flux = A.st_flux * tw
    m = (px > -400) & (px < W + 400) & (py > -400) & (py < H + 400)
    px, py, flux, col, sig = px[m], py[m], flux[m], A.st_col[m], A.st_sig[m]
    if lens is None or lens[3] <= 0.01:
        splat(acc, px, py, col * flux[:, None], sig)
        return
    sig_px = np.array(A.sig)[sig]
    for ix, iy, mu, stretch, rad, ang in lens_images(px, py, lens):
        keep = mu > 1e-3
        mu, stretch, rad, ang, f0, sg, spx = mu[keep], stretch[keep], rad[keep], ang[keep], \
            (col * flux[:, None])[keep], sig[keep], sig_px[keep]
        length = np.clip(spx * 2.2 * (stretch - 1), 0, 70)
        K = np.clip(np.ceil(length / (0.9 * spx)), 1, 40).astype(int)  # sub-dots <= 0.9 sigma apart
        rep_i = np.repeat(np.arange(len(K)), K)
        j = np.arange(len(rep_i)) - np.repeat(np.cumsum(K) - K, K)
        frac = np.where(K[rep_i] > 1, j / np.maximum(K[rep_i] - 1, 1) - 0.5, 0.0)
        a = ang[rep_i] + frac * length[rep_i] / np.maximum(rad[rep_i], 1)
        x = lens[0] + rad[rep_i] * np.cos(a)
        y = lens[1] + rad[rep_i] * np.sin(a)
        f = f0[rep_i] * (mu / K)[rep_i][:, None]
        splat(acc, x, y, f, sg[rep_i])


def lens_map(xs, ys, lens):
    """Backward map: screen points -> where their light came from (point lens)."""
    if lens is None or lens[3] <= 0.01:
        return xs, ys
    cx, cy, rs, th_e, _ = lens
    u, v = (xs - cx) / rs, (ys - cy) / rs
    r2 = np.maximum(u * u + v * v, 0.04)
    k = 1 - th_e ** 2 / r2
    return cx + u * k * rs, cy + v * k * rs


def upscale(img_small):
    """Bilinear upscale of an (h, w, 3) float image to full frame."""
    return np.stack([np.asarray(Image.fromarray(np.ascontiguousarray(img_small[..., c]), 'F')
                                .resize((W, H), Image.BILINEAR)) for c in range(img_small.shape[2])], axis=-1)


def render_nebula(t, cam, lens, grid=0.0):
    """Faint dust clouds (and the optional space-time grid), lensed. Quarter/half resolution."""
    q = 4
    ys, xs = np.mgrid[0:H // q, 0:W // q].astype(np.float32)
    xs, ys = xs * q + q / 2, ys * q + q / 2
    sx, sy = lens_map(xs, ys, lens)
    d = 0.12
    z = cam.zoom ** d
    drift = np.array([-6.0, -2.5]) * t
    wx = (sx - ANCHOR[0] - cam.shake[0]) / z - (drift[0] + cam.bg[0]) * d
    wy = (sy - ANCHOR[1] - cam.shake[1]) / z - (drift[1] + cam.bg[1]) * d
    (ox, oy), s = A.neb_box
    coords = [(wy - oy) / s, (wx - ox) / s]
    neb = np.stack([ndimage.map_coordinates(A.nebula[..., c], coords, order=1, mode='mirror')
                    for c in range(3)], axis=-1)
    out = upscale(neb.astype(np.float32))
    if grid > 0.01 and lens is not None:
        out += render_grid(lens, grid)
    return out


def render_grid(lens, amount):
    """A flat space-time grid behind the hole, bent by the same lens (half resolution)."""
    q = 2
    ys, xs = np.mgrid[0:H // q, 0:W // q].astype(np.float32)
    xs, ys = xs * q + q / 2, ys * q + q / 2
    sx, sy = lens_map(xs, ys, lens)
    cx, cy, rs, th_e, _ = lens
    rho = np.hypot(xs - cx, ys - cy) / rs
    gu, gv = (sx - cx) / rs / 0.5, (sy - cy) / rs / 0.5
    line = np.maximum(np.exp(-((gu - np.round(gu)) / 0.035) ** 2), np.exp(-((gv - np.round(gv)) / 0.035) ** 2))
    wgt = smoothstep(1.7, 2.3, rho) * np.exp(-(rho / 3.6) ** 2) * amount
    g = (line * wgt)[..., None] * np.array([0.16, 0.45, 0.95], np.float32) * 0.32
    return upscale(g.astype(np.float32))


def background(t, cam, lens=None, grid=0.0, stars=1.0):
    acc = np.zeros((3, H * W), np.float64)
    render_stars(acc, t, cam, lens)
    img = acc.reshape(3, H, W).transpose(1, 2, 0).astype(np.float32) * stars
    img += render_nebula(t, cam, lens, grid)
    return img


def box(c, rx, ry):
    x0, x1 = int(max(0, c[0] - rx)), int(min(W, c[0] + rx + 1))
    y0, y1 = int(max(0, c[1] - ry)), int(min(H, c[1] + ry + 1))
    return x0, x1, y0, y1


def render_star(img, t, c, R, bright=1.0, temp=0.62, turb=1.0, corona=1.0, infall=0.0, R_lag=None):
    x0, x1, y0, y1 = box(c, R * 4.2, R * 4.2)
    if x1 <= x0 or y1 <= y0 or R < 0.3:
        return
    yy, xx = np.mgrid[y0:y1, x0:x1].astype(np.float32)
    dx, dy = (xx - c[0]) / R, (yy - c[1]) / R
    d = np.hypot(dx, dy)
    ang = np.arctan2(dy, dx)
    # surface
    inside = d < 1.0
    nx, ny = np.clip(dx, -1, 1), np.clip(dy, -1, 1)
    mu = np.sqrt(np.clip(1 - d * d, 0, 1))
    lon = np.arctan2(nx, np.maximum(mu, 1e-3)) + 0.05 * t
    lat = np.arcsin(np.clip(ny, -1, 1))
    gh, gw = A.gran.shape
    tex = ndimage.map_coordinates(A.gran, [(lat / np.pi + 0.5) * (gh - 1), (lon / (2 * np.pi)) * gw + t * 3.0],
                                  order=1, mode='grid-wrap')
    tex = 0.5 + (tex - 0.5) * turb
    T = temp * (0.8 + 0.4 * tex) * (0.8 + 0.25 * mu)
    I = bright * (0.25 + 0.75 * mu ** 0.5) * (0.5 + 1.0 * tex) * 1.7
    surf = palette(T) * I[..., None]
    alpha = np.clip((1 - d) * R + 0.5, 0, 1)[..., None] * inside[..., None]
    # corona with slowly turning rays
    q = np.maximum(d - 1, 0)
    ri = ((ang / (2 * np.pi) + 0.5) * len(A.rays) + t * 12) % len(A.rays)
    rays = np.interp(ri, np.arange(len(A.rays)), A.rays, period=len(A.rays))
    cor = corona * bright * (1.1 * np.exp(-q / 0.04) + 0.35 * np.exp(-q / 0.2) * (0.3 + 1.4 * rays)
                             + 0.045 * np.exp(-q / 0.9))
    out = surf * alpha + (1 - alpha) * cor[..., None] * palette(temp * 0.9)
    if infall > 0 and R_lag is not None:        # outer layers raining inward during collapse
        dl = np.hypot(xx - c[0], yy - c[1])
        streak = np.exp(-((dl - R_lag) / (R_lag * 0.22 + 4)) ** 2) * (0.25 + 1.6 * rays ** 3)
        out += (infall * streak)[..., None] * palette(temp * 1.1) * 1.5
    img[y0:y1, x0:x1] += out


def render_point(img, c, inten, size, temp=1.3):
    """A tiny hot core with a soft glow."""
    if inten <= 0.01:
        return
    x0, x1, y0, y1 = box(c, size * 14, size * 14)
    if x1 <= x0 or y1 <= y0:
        return
    yy, xx = np.mgrid[y0:y1, x0:x1].astype(np.float32)
    d = np.hypot(xx - c[0], yy - c[1]) / size
    g = 4.0 * np.exp(-d * d) + 0.5 * np.exp(-d / 2.2) + 0.08 * np.exp(-d / 7)
    img[y0:y1, x0:x1] += (inten * g)[..., None] * palette(temp)


def render_supernova(img, te, c, zoom, amount=1.0):
    """Explosion te seconds after detonation: shock ring, filamentary ejecta, god rays."""
    if te < -0.2 or amount <= 0.001:
        return
    q = 2
    ys, xs = np.mgrid[0:H // q, 0:W // q].astype(np.float32)
    dx, dy = xs * q - c[0], ys * q - c[1]
    d = np.hypot(dx, dy) + 1e-3
    ang = np.arctan2(dy, dx)
    te = max(te, 0.0)
    Rs = zoom * (60 + 820 * (1 - math.exp(-te / 1.5)) + 40 * te)
    u = d / Rs
    nf, nu = A.fil.shape
    fil = ndimage.map_coordinates(A.fil, [(ang / (2 * np.pi) + 0.5) * nf, np.clip(u * 0.7 + te * 0.06, 0, 2) * (nu - 1) / 2],
                                  order=1, mode='grid-wrap')
    shell = smoothstep(0.25, 0.85, u) * (1 - smoothstep(0.9, 1.04, u)) * fil
    col = (np.array([0.35, 0.65, 1.0], np.float32) * (1 - smoothstep(0.45, 0.95, u))[..., None]
           + np.array([1.0, 0.42, 0.12], np.float32) * smoothstep(0.45, 0.95, u)[..., None])
    ej = (2.6 * math.exp(-te / 0.6) + 0.42 * math.exp(-te / 4.5))
    out = shell[..., None] * col * ej
    ring = np.exp(-((u - 1.0) / 0.018) ** 2) * (2.5 * math.exp(-te / 0.55) + 0.25 * math.exp(-te / 3))
    out += ring[..., None] * np.array([0.8, 0.9, 1.0], np.float32)
    ri = (ang / (2 * np.pi) + 0.5) * len(A.rays)
    rays = np.interp(ri, np.arange(len(A.rays)), A.rays, period=len(A.rays)) ** 3
    gr = rays * np.exp(-d / (zoom * (250 + 600 * te))) * 5.0 * math.exp(-te / 0.4)
    out += gr[..., None] * np.array([1.0, 0.85, 0.65], np.float32)
    core_glow = 7.0 * math.exp(-te / 0.35) / (1 + (d / (90 * zoom)) ** 2)
    out += core_glow[..., None] * np.array([0.9, 0.93, 1.0], np.float32)
    flare = 2.2 * math.exp(-te / 0.5) * np.exp(-(dy / 5) ** 2) * np.exp(-np.abs(dx) / 520)
    out += flare[..., None] * np.array([0.55, 0.75, 1.0], np.float32)
    img += upscale((out * amount).astype(np.float32))


def render_black_hole(img, t, c, rs, incl, roll, disk=1.0, swirl=1.0, r_out=DISK_ROUT, ring=1.0):
    """Shadow, photon ring, Doppler-beamed accretion disk + its lensed far side (in place)."""
    if rs < 0.6:
        return
    ci, si = math.cos(incl), math.sin(incl)
    hw = (r_out + 0.3) * rs
    hh = max(2.3 * rs, hw * (abs(math.sin(roll)) + ci) + 0.5 * rs)
    x0, x1, y0, y1 = box(c, max(hw, 2.3 * rs), hh)
    if x1 <= x0 or y1 <= y0:
        return
    yy, xx = np.mgrid[y0:y1, x0:x1].astype(np.float32)
    dx, dy = xx - c[0], yy - c[1]
    cr, sr = math.cos(roll), math.sin(roll)
    u = (dx * cr + dy * sr) / rs
    v = (-dx * sr + dy * cr) / rs
    rho = np.hypot(u, v)
    mask = np.clip((rho - 1) * rs + 0.5, 0, 1)            # 0 inside the shadow
    emis = np.zeros(u.shape + (3,), np.float32)
    rin = DISK_RIN
    nr, nphi = A.disk.shape

    def disk_light(r, psi, wgt):
        """Emission of disk material at radius r / azimuth psi (arrays, already selected)."""
        omega = 1.1 * swirl * (rin / r) ** 1.5
        ri = np.clip((r - rin) / (r_out - rin), 0, 1) * (nr - 1)
        pi = ((psi + omega * t) / (2 * np.pi)) * nphi
        tex = ndimage.map_coordinates(A.disk, [ri, pi], order=1, mode='grid-wrap')
        vel = 0.45 * np.sqrt(rin / r)
        los = -np.cos(psi) * vel * si                       # + = moving towards us (left side)
        g = 1 / (np.sqrt(1 - vel ** 2) * (1 - los))
        temp = (rin / r) ** 0.6 * g ** 0.8 * (0.62 + 0.28 * tex)
        inten = (rin / r) ** 1.4 * g ** 3 * tex * 0.85 * wgt
        return palette(temp) * inten[:, None]

    if disk > 0.001:
        # direct image of the thin, inclined disk
        X, Y = u, v / ci
        r = np.hypot(X, Y)
        prof = smoothstep(rin - 0.04, rin + 0.18, r) * (1 - smoothstep(r_out * 0.5, r_out, r))
        vis = np.where(v > 0, 1.0, mask)                    # far half hides behind the shadow
        wgt = prof * vis * disk
        sel = wgt > 2e-3
        if sel.any():
            emis[sel] += disk_light(r[sel], np.arctan2(Y[sel], X[sel]), wgt[sel])
        # lensed image of the far side, wrapped over the top (and faintly under the bottom)
        s = v / np.maximum(rho, 1e-3)
        width = 0.16 + 0.42 * np.clip(-s, 0, 1) ** 1.3
        hr = (rho - 1.035) / width
        hal = smoothstep(-0.02, 0.1, hr) * (1 - smoothstep(0.45, 1.0, hr))
        hal *= (0.42 + 0.58 * np.clip(-s, 0, 1) ** 0.6) * mask * disk
        sel = hal > 2e-3
        if sel.any():
            rh = rin + np.clip(hr[sel], 0, 1) * (r_out * 0.7 - rin)
            psi = np.arctan2(-np.abs(v[sel]), u[sel])
            emis[sel] += disk_light(rh, psi, hal[sel] * 0.75)
    if ring > 0.001:
        wpx = max(0.012, 1.1 / rs)
        pr = (1.6 * np.exp(-((rho - 1.012) / wpx) ** 2) + 0.22 * np.exp(-((rho - 1.0) / 0.07) ** 2) * mask)
        pr *= (1 + 0.55 * np.clip(-u / np.maximum(rho, 1e-3), -1, 1)) * ring
        emis += pr[..., None] * np.array([1.0, 0.86, 0.62], np.float32)
        glow = 0.05 * np.exp(-(rho - 1) / 1.2) * mask * ring * (1 - smoothstep(1.6, 2.2, rho))
        emis += glow[..., None] * np.array([1.0, 0.55, 0.2], np.float32)
    img[y0:y1, x0:x1] = img[y0:y1, x0:x1] * mask[..., None] + emis


def spaghetti_particles(t):
    """Positions (shadow units, relative to the hole) and brightness of the infalling body."""
    key = 'spag'
    if key not in A.cache:
        rng = np.random.default_rng(5)
        n = 1600
        o = rng.standard_normal((n, 2)) * 0.5
        o *= (1 + 0.25 * rng.standard_normal((n, 1)))     # lumpy rock
        A.cache[key] = (o.astype(np.float32), rng.uniform(0.4, 1.0, n).astype(np.float32),
                        rng.uniform(0, 1, n).astype(np.float32))
    o, lum, jit = A.cache[key]
    p = clamp01((t - EV['obj_in']) / (EV['obj_end'] - EV['obj_in']))
    s_obj = p ** 1.55

    def path(s):
        rho = 1.0 + 2.9 * (1 - s) ** 1.25
        phi = -0.95 + 3.4 * s
        return rho * np.cos(phi), rho * np.sin(phi)

    st = smoothstep(EV['stretched'] - 0.35, EV['pulled'] + 0.1, t)
    ap = smoothstep(EV['pulled'] - 0.1, EV['obj_end'], t)
    S = 1 + 5.5 * st ** 1.6 + 6 * ap
    size = 0.17
    cx, cy = path(s_obj)
    rad = np.array([-cx, -cy]) / math.hypot(cx, cy)
    tan = np.array([-rad[1], rad[0]])
    # torn apart: each bit runs ahead/behind along the orbit by its radial offset
    s_i = np.clip(s_obj - o[:, 0] * 0.09 * ap * (1 + jit), 0, 1)
    px, py = path(s_i)
    off_r = o[:, 0] * size * S * (1 - 0.7 * ap)
    off_t = o[:, 1] * size / np.sqrt(S)
    x = px + rad[0] * off_r + tan[0] * off_t
    y = py + rad[1] * off_r + tan[1] * off_t
    heat = st * 0.7 + ap * 0.5
    b = lum * (1.0 + 2.4 * heat) * smoothstep(0, 0.05, p) * (1 - smoothstep(0.985, 1.0, s_i))
    return x, y, b, heat, (cx, cy)


def render_spaghetti(img, t, c, rs, roll):
    if t < EV['obj_in'] or t > EV['obj_end'] + 0.2:
        return None
    x, y, b, heat, (cx, cy) = spaghetti_particles(t)
    rho = np.hypot(x, y)
    b = b * smoothstep(1.0, 1.05, rho)                       # swallowed by the shadow
    cr, sr = math.cos(roll), math.sin(roll)
    sx = c[0] + (x * cr - y * sr) * rs
    sy = c[1] + (x * sr + y * cr) * rs
    col = palette(np.full(len(x), 0.55 + 0.45 * heat)) * (0.5 + 0.5 * heat)
    rock = np.array([0.75, 0.68, 0.62], np.float32) * (1 - heat)
    f = (col + rock) * b[:, None] * 1.6
    acc = np.zeros((3, H * W))
    splat(acc, sx, sy, f, np.full(len(x), 3))
    img += acc.reshape(3, H, W).transpose(1, 2, 0).astype(np.float32)
    ox, oy = c[0] + (cx * cr - cy * sr) * rs, c[1] + (cx * sr + cy * cr) * rs
    if math.hypot(cx, cy) > 1.05:                     # warm glow around the intact body
        render_point(img, (ox, oy), 0.25 * (1 - smoothstep(EV['pulled'] - 0.2, EV['pulled'] + 0.5, t)),
                     6 + 6 * heat, temp=0.6 + 0.3 * heat)
    return ox, oy


# ----------------------------------------------------------------- post: bloom, tone map, grain

def bloom(img, holes=()):
    small = img.reshape(H // 4, 4, W // 4, 4, 3).mean(axis=(1, 3))
    b1 = ndimage.gaussian_filter(small, (3, 3, 0))
    b2 = ndimage.gaussian_filter(small, (16, 16, 0))
    streak = ndimage.gaussian_filter1d(np.maximum(small - 1.2, 0), 45, axis=1)
    glow = 0.15 * b1 + 0.13 * b2 + 0.05 * streak * np.array([0.7, 0.8, 1.0], np.float32)
    if holes:                      # the shadow stays black: no glow spills into it
        ys, xs = np.mgrid[0:H // 4, 0:W // 4].astype(np.float32) * 4 + 2
        for cx, cy, r in holes:
            d = np.hypot(xs - cx, ys - cy) / max(r, 1)
            glow *= (0.06 + 0.94 * smoothstep(0.82, 1.02, d))[..., None]
    return img + upscale(glow.astype(np.float32))


def finish(img, fi, exposure=1.0, holes=()):
    img = bloom(img, holes) * exposure
    a, b, c, d, e = 2.51, 0.03, 2.43, 0.59, 0.14                # ACES filmic
    x = np.clip((img * (a * img + b)) / (img * (c * img + d) + e), 0, 1)
    x = x ** (1 / 2.2) * A.vignette
    g = A.grain[fi % len(A.grain)]
    g = np.roll(g, (fi * 397) % H, axis=0)
    lum = x.mean(axis=2, keepdims=True)
    x = x + g[..., None].astype(np.float32) * (0.004 + 0.08 * lum * (1 - lum))
    return np.clip(x, 0, 1)


# ----------------------------------------------------------------- overlays (display space)

def blend(frame, rgb, alpha, x0, y0):
    """Alpha-blend an (h, w, 3) patch at (x0, y0), clipped to the frame."""
    h, w = alpha.shape
    fx0, fy0, fx1, fy1 = max(0, x0), max(0, y0), min(W, x0 + w), min(H, y0 + h)
    if fx1 <= fx0 or fy1 <= fy0:
        return
    a = alpha[fy0 - y0:fy1 - y0, fx0 - x0:fx1 - x0, None]
    p = rgb[fy0 - y0:fy1 - y0, fx0 - x0:fx1 - x0]
    frame[fy0:fy1, fx0:fx1] = frame[fy0:fy1, fx0:fx1] * (1 - a) + p * a


def add_glow(frame, mask, color, x0, y0):
    """Additive coloured glow from a mask placed at (x0, y0), clipped to the frame."""
    h, w = mask.shape
    fx0, fy0, fx1, fy1 = max(0, x0), max(0, y0), min(W, x0 + w), min(H, y0 + h)
    if fx1 > fx0 and fy1 > fy0:
        frame[fy0:fy1, fx0:fx1] += mask[fy0 - y0:fy1 - y0, fx0 - x0:fx1 - x0, None] * np.array(color, np.float32)


def text_mask(text, font, tracking=0.0):
    """Antialiased text mask with letter spacing, as float (h, w)."""
    widths = [font.getlength(ch) + tracking for ch in text]
    asc, desc = font.getmetrics()
    wtot = int(sum(widths) - tracking + 8)
    im = Image.new('L', (max(wtot, 1), asc + desc + 8), 0)
    dr = ImageDraw.Draw(im)
    x = 4.0
    for ch, cw in zip(text, widths):
        dr.text((x, 4), ch, font=font, fill=255)
        x += cw
    return np.asarray(im, np.float32) / 255.0


def soft(mask, radius):
    im = Image.fromarray((np.clip(mask, 0, 1) * 255).astype(np.uint8))
    return np.asarray(im.filter(ImageFilter.GaussianBlur(radius)), np.float32) / 255.0


def pad_mask(m, p):
    return np.pad(m, p)


def draw_text(frame, text, font, x, y, color=(1, 1, 1), alpha=1.0, tracking=0.0, align='left',
              shadow=0.75, glow=None):
    key = ('txt', text, id(font), tracking)
    if key not in A.cache:
        m = pad_mask(text_mask(text, font, tracking), 24)
        A.cache[key] = (m, soft(m, 8), soft(m, 14))
    m, sh, gl = A.cache[key]
    h, w = m.shape
    x0 = int(x - (w / 2 if align == 'center' else 24))
    y0 = int(y - h / 2)
    if shadow:
        blend(frame, np.zeros((h, w, 3), np.float32), sh * shadow * alpha, x0, y0 + 3)
    if glow is not None:
        add_glow(frame, gl * 0.5 * alpha, glow, x0, y0)
    blend(frame, np.broadcast_to(np.array(color, np.float32), (h, w, 3)), m * alpha, x0, y0)
    return w - 48


def draw_line(frame, p, q, alpha, width=1.6, color=(1, 1, 1)):
    """Antialiased line segment."""
    p, q = np.asarray(p, float), np.asarray(q, float)
    x0, x1, y0, y1 = box((p + q) / 2, abs(q[0] - p[0]) / 2 + 4, abs(q[1] - p[1]) / 2 + 4)
    if x1 <= x0 or y1 <= y0:
        return
    yy, xx = np.mgrid[y0:y1, x0:x1].astype(np.float32)
    ab = q - p
    k = np.clip(((xx - p[0]) * ab[0] + (yy - p[1]) * ab[1]) / max(ab @ ab, 1e-6), 0, 1)
    d = np.hypot(xx - p[0] - k * ab[0], yy - p[1] - k * ab[1])
    a = np.clip(width - d, 0, 1) * alpha
    blend(frame, np.broadcast_to(np.array(color, np.float32), a.shape + (3,)), a, x0, y0)


def draw_ring_label(frame, c, r, rs, prog, alpha):
    """Dashed circle (drawn on) inside the shadow + leader line + 'EVENT HORIZON' label above."""
    if alpha <= 0.01:
        return
    x0, x1, y0, y1 = box(c, r + 8, r + 8)
