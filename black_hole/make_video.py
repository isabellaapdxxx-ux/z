    for name, t in moments.items():
        fi = int(round(t * FPS))
        Image.fromarray(render_frame(fi)).save(os.path.join(d, f'{name}_{fi / FPS:05.2f}s.png'))
        log(f'  {name} @ {fi / FPS:.2f}s')
