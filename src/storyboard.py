"""Generate STORYBOARD.md from the shot list, the script and the measured VO timings."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from script_data import LINES, TITLES  # noqa: E402
from shots import SHOTS  # noqa: E402

SECTIONS = [
    (0.0, 6.05, 'HOOK (0:00-0:06)'),
    (6.05, 30.0, '1. Normal day (0:06-0:30)'),
    (30.0, 55.0, '2. Discovery (0:30-0:55)'),
    (55.0, 75.0, '3. The call (0:55-1:15)'),
    (75.0, 104.6, '4. Kidnapped (1:15-1:45)'),
    (104.6, 115.0, '5. Rescue (1:45-1:55)'),
    (115.0, 120.0, '6. Ending (1:55-2:00)'),
]

SPEAKER = {'narr': 'Boy (narration)', 'boy': 'Boy', 'whisper': 'Boy (whisper)', 'cousin': 'Cousin',
           'cousin_nice': 'Cousin (friendly)', 'operator': '911 operator', 'cop': 'Police officer'}

SFX = {
    'HOOK (0:00-0:06)': 'Frame 1: bass hit + "call dropped" beeps, then silence with heartbeat and slow footsteps; '
                        'whoosh + light hit on the face zoom; tape-rewind + glitch into the flashback.',
    '1. Normal day (0:06-0:30)': 'Birds, footsteps, door creak. Theme: eerie music-box loop with a light beat, '
                                 'thins out in the hallway. Bass hits on "LOCKED" and when the smile drops.',
    '2. Discovery (0:30-0:55)': 'Car driving away, keys jingle, footsteps, unlock click, long door creak. '
                                'Music turns dark (low drone, detuned music box). Bass hits on "MISSING", '
                                'the name reveal and "KILLER"; gasp; front door slam.',
    '3. The call (0:55-1:15)': 'Rustle, DTMF 9-1-1 dialing, ring-back, connect click, operator on a phone filter, '
                               'whisper, footsteps getting louder, closet creak, bass hit on "Found you", '
                               'call-dropped beeps and hard cut to black with heartbeat. Pulsing tension ostinato.',
    '4. Kidnapped (1:15-1:45)': 'Gasp on waking, footsteps, phone smash (crack + glass), bass hits, ticking clock '
                                'and heartbeat throughout, footsteps up the stairs, door shut, struggling chair '
                                'creaks, door creak, footsteps down, gasp. Theme returns with taiko drums and '
                                'tremolo strings and keeps intensifying, then a riser.',
    '5. Rescue (1:45-1:55)': 'Sirens, door bash, running footsteps, handcuffs ratchet click. Theme flips to a '
                             'heroic A-major brass + march snare version.',
    '6. Ending (1:55-2:00)': 'Distant siren, music box theme back in minor, sting + bass hit on "Part 2?", '
                             'glitch + riser that lands on the frame-1 bass hit when the video loops.',
}


def ts(t):
    m = int(t // 60)
    s = t - 60 * m
    return f'{m}:{s:05.2f}'


def main():
    timing = json.load(open(os.path.join(ROOT, 'build', 'vo_timing.json')))
    tl = {L['id']: L for L in timing['lines']}
    out = ['# Storyboard / script: "My cousin heard me call 911..."', '',
           'A 2:00 vertical (1080x1920, 30 fps) Roblox-style horror story. All visuals, voices, music and SFX '
           'are generated by the code in `src/`. The characters and sets are original blocky designs '
           '(no Roblox assets or logos). Timestamps are `m:ss.ss`. Voice timings are the measured lengths of '
           'the generated TTS.', '',
           'Captions pop in word by word, synced to the voice. Key words are shown in red.', '']
    for s0, s1, name in SECTIONS:
        out += [f'## {name}', '', '| Time | Shot |', '|---|---|']
        for t0, t1, fn, desc in SHOTS:
            if s0 <= t0 < s1:
                out.append(f'| {ts(t0)}–{ts(t1)} | {desc} |')
        out += ['', '**Voice / captions**', '']
        for lid, start, spk, text, _ in LINES:
            if s0 <= start < s1:
                L = tl[lid]
                cap = text.replace('*', '**')
                out.append(f'- `{ts(L["start"])}–{ts(L["end"])}` {SPEAKER[spk]}: {cap}')
        for t0, t1, text in TITLES:
            if s0 <= t0 < s1:
                out.append(f'- `{ts(t0)}–{ts(t1)}` Title card: **{text}**')
        out += ['', f'**Sound:** {SFX[name]}', '']
    out += ['## Loop', '',
            'The last 0.7 s glitch back into the exact camera and pose of frame 1 (the boy tied up, phone '
            'showing "911 call ended"). The riser at the end lands on the frame-1 bass hit, so the video '
            'loops smoothly when it replays.', '']
    with open(os.path.join(ROOT, 'STORYBOARD.md'), 'w') as f:
        f.write('\n'.join(out))
    print('wrote STORYBOARD.md')


if __name__ == '__main__':
    main()
